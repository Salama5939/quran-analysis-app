def smart_parse_reference_string(reference_text):
    """
    محرك الـ Parser الذكي المتطور:
    - يقسم النص بناءً على الشرطة '-' لاعتبار كل جزء وحدة مستقلة.
    - يتتبع رقم السورة (اليمين لـ '/') ويورثها للآيات التالية داخل نفس الوحدة إذا لم توجد شرائط جديدة.
    """
    parsed_records = []
    segments = re.split(r"\s*-\s*", reference_text.strip())

    current_surah = None

    for segment in segments:
        segment = segment.strip()
        if not segment:
            continue

        # إذا وجدنا علامة '/' فهذا معناه وجود سورة جديدة في هذا المقطع
        if "/" in segment:
            parts = segment.split("/")
            current_surah = parts[0].strip()  # اليمين = رقم السورة
            ayahs_part = parts[1].strip()  # اليسار = أرقام الآيات
        else:
            # إذا لم يوجد '/', فهذا معناه آيات تتبع نفس السورة الحالية (السياق المتورث)
            ayahs_part = segment

        # استخراج كافة أرقام الآيات الواردة في هذا المقطع
        ayah_numbers = re.findall(r"\d+", ayahs_part)

        if current_surah and ayah_numbers:
            s_num = int(current_surah)
            for ayah in ayah_numbers:
                a_num = int(ayah)
                parsed_records.append((s_num, a_num))

    return parsed_records


