if __name__ == "__main__":
    try:
        # 1. قراءة ملف الأكسل المعتمد الجديد
        excel_filename = "My data sheet unit now dated 04112026.xlsx"
        df = pd.read_excel(excel_filename)
        print(f"📂 تم قراءة ملف الأكسل بنجاح، إجمالي السجلات: {len(df)}")

        # 2. الاتصال بقاعدة بيانات Supabase عبر الأسرار
        url = st.secrets["SUPABASE_URL"]
        key = st.secrets["SUPABASE_KEY"]
        supabase = create_client(url, key)
        print("🔗 تم الاتصال بقاعدة بيانات Supabase بنجاح...")

        # 3. تفريغ جدول quran_topics أولاً لضمان البدء بنظافة تامة
        supabase.table("quran_topics").delete().neq("id", 0).execute()
        print("🗑️ تم تفريغ جدول quran_topics بنجاح استعداداً للرفع الشامل.")

        # 4. تجهيز وتحويل السجلات لهيكل Supabase الهرمي
        records_to_insert = []
        for _, row in df.iterrows():
            s_num = int(row["رقم السورة"])
            a_num = int(row["رقم الآية"])
            page_num = int(row["رقم الصفحة"])
            s_name = SURAH_NAMES_AR.get(s_num, "غير محدد")

            records_to_insert.append(
                {
                    "main_chapter": "الباب الأول: أركان الإسلام",
                    "section_name": "الفصل الأول: التوحيد",
                    "topic_heading": "أولاً: توحيد الله",
                    "topic_category": "التوحيد والعقيدة",
                    "topic_sub_category": "1- وجوده تعالى وقيامه وكفر البيان والمالية",
                    "surah_number": s_num,
                    "surah_name_ar": s_name,
                    "start_ayah": a_num,
                    "end_ayah": a_num,
                    "topic_description": f"مرجع من صفحة الكتيب رقم {page_num}",
                }
            )

        # تقسيم السجلات إلى دفعات (Batches of 100) لضمان الاستقرار السحابي
        batch_size = 100
        total_inserted = 0
        for i in range(0, len(records_to_insert), batch_size):
            batch = records_to_insert[i : i + batch_size]
            response = supabase.table("quran_topics").insert(batch).execute()
            total_inserted += len(batch)
            print(f"⏳ تم رفع دفعة بنجاح... الإجمالي حتى الآن: {total_inserted} سجلاً")

        print(
            f"✅ تم الانتهاء بنجاح تام! تم ترحيل جميع السجلات ({total_inserted} سجل) إلى Supabase!"
        )

    except Exception as e:
        print(f"❌ حدث خطأ أثناء عملية الترحيل: {e}")
