# 1. تبديل الأعمدة: وضعنا السورة في العمود الذي سيظهر يميناً، والآيات يساراً
col2, col1 = st.columns([1, 1])

with col2:
    # 2. البحث باسم السورة بدلاً من رقمها
    surah_name = st.selectbox("اختر السورة:", surahs)
    # الحصول على رقم السورة برمجياً بناءً على ترتيبها في القائمة (يبدأ من 0 فنضيف 1)
    surah_num = surahs.index(surah_name) + 1

with col1:
    # 3. إتاحة البحث بنطاق (من - إلى)
    c_start, c_end = st.columns(2)
    with c_start:
        ayah_start = st.number_input("من آية رقم:", min_value=1, value=1, step=1)
    with c_end:
        ayah_end = st.number_input("إلى آية رقم:", min_value=1, value=1, step=1)

# زر التشغيل
if st.button("▶️ جلب وتشغيل الآيات", type="primary", use_container_width=True):
    # التحقق من المنطق الرياضي للأرقام
    if ayah_start > ayah_end:
        st.error("❌ خطأ هندسي: يجب أن تكون آية البداية أصغر من أو تساوي آية النهاية.")
    else:
        with st.spinner("جاري الاتصال بالخادم وجلب التلاوات المطلوبة..."):

            st.success(
                f"✅ تم جلب سورة {surah_name} (رقم {surah_num}) من آية {ayah_start} إلى آية {ayah_end}"
            )

            # حلقة تكرارية (Loop) لجلب الآيات المطلوبة بالترتيب
            for ayah in range(ayah_start, ayah_end + 1):
                # تجهيز صيغة الأرقام الثلاثية (مثال: 002 و 255)
                surah_str = f"{surah_num:03d}"
                ayah_str = f"{ayah:03d}"

                # بناء رابط الملف الصوتي
                audio_url = f"https://everyayah.com/data/Maher_AlMuaiqly_64kbps/{surah_str}{ayah_str}.mp3"

                # عرض مشغل الصوت لكل آية
                st.markdown(
                    f"<p style='font-size: 16px; font-weight: bold; margin-bottom: 0px;'>آية رقم ({ayah})</p>",
                    unsafe_allow_html=True,
                )
                st.audio(audio_url, format="audio/mp3")
