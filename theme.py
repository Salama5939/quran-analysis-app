def add_home_button():
    """دالة مساعدة لإضافة زر سريع للعودة للصفحة الرئيسية في أعلى الصفحات الفرعية"""
    col1, col2, col3 = st.columns([1, 4, 1])
    with col1:
        if st.button("🏠 الرئيسية", width="stretch", key="global_home_btn"):
            st.switch_page("Home.py")


def render_page_guide(gate_key: str):
    """عرض بطاقة إرشادية تفاعلية قابلة للطي تشرح هدف البوابة وتبويباتها وطريقة استخدامها"""
    guide = GATE_GUIDES.get(gate_key)
    if not guide:
        return

    with st.expander(f"📘 {guide['title']} — (اضغط للفتح أو الإغلاق)", expanded=False):
        tabs_html = "".join(
            f"<div class='gate-guide-tab-item'><b>🔹 {t_name}:</b> {t_desc}</div>"
            for t_name, t_desc in guide["tabs"]
        )
        st.markdown(
            f"""
            <div class="gate-guide-box">
                <div class="gate-guide-section-title">🎯 الهدف من هذه البوابة:</div>
                <div>{guide['goal']}</div>
                <div class="gate-guide-section-title">📑 مكونات البوابة وتبويباتها:</div>
                {tabs_html}
                <div class="gate-guide-section-title">🚀 طريقة الاستخدام السريعة:</div>
                <div>{guide['steps']}</div>
            </div>
            """,
            unsafe_allow_html=True,
        )
